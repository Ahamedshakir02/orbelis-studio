/**
 * Runs after `vite build`: writes the rendered pages, the structured data,
 * llms.txt and sitemap.xml into dist/.
 *
 * Without this the served HTML is an empty <div id="root">, and anything that
 * reads the page without running JavaScript (most AI crawlers, link previews,
 * Bing on a bad day) sees a blank page with a title.
 *
 *   1. Build src/entry-server.jsx for Node into a temporary folder.
 *   2. Render each page and put the markup inside its #root.
 *   3. Write the JSON-LD into the home page's <head>.
 *   4. Write llms.txt from site.js.
 *   5. Write sitemap.xml, each page's <lastmod> taken from the last git commit
 *      that touched its content, so it only moves when the page really did.
 */
import { build } from 'vite'
import { execFileSync } from 'node:child_process'
import { readFileSync, writeFileSync, rmSync } from 'node:fs'
import { resolve, dirname } from 'node:path'
import { fileURLToPath, pathToFileURL } from 'node:url'

const root = resolve(dirname(fileURLToPath(import.meta.url)), '..')
const dist = resolve(root, 'dist')
const tmp = resolve(root, 'node_modules/.prerender')
const site = 'https://orbelisstudio.com'

await build({
  root,
  logLevel: 'warn',
  build: { ssr: 'src/entry-server.jsx', outDir: tmp, emptyOutDir: true, rollupOptions: { input: undefined } },
})

const { render, structuredDataTag, llmsTxt } = await import(pathToFileURL(resolve(tmp, 'entry-server.js')).href)

const pages = [
  { file: 'index.html', page: 'main' },
  { file: 'privacy.html', page: 'privacy' },
  { file: 'terms.html', page: 'terms' },
  { file: '404.html', page: 'notfound' },
]

for (const { file, page } of pages) {
  const path = resolve(dist, file)
  let html = readFileSync(path, 'utf8')
  const empty = '<div id="root"></div>'
  if (!html.includes(empty)) throw new Error(`${file}: no empty #root to render into`)
  html = html.replace(empty, `<div id="root">${render(page)}</div>`)
  if (page === 'main') html = html.replace('</head>', `  ${structuredDataTag()}\n  </head>`)
  writeFileSync(path, html)
}

writeFileSync(resolve(dist, 'llms.txt'), llmsTxt())

/** Date of the last commit touching any of `paths`, or today outside git. */
function lastmod(paths) {
  try {
    const d = execFileSync('git', ['log', '-1', '--format=%cs', '--', ...paths], { cwd: root, encoding: 'utf8' }).trim()
    if (d) return d
  } catch {}
  return new Date().toISOString().slice(0, 10)
}

const urls = [
  { loc: '/', paths: ['index.html', 'src/data/site.js', 'src/sections', 'src/components'], freq: 'monthly', priority: '1.0' },
  { loc: '/privacy', paths: ['privacy.html', 'src/data/legal.js'], freq: 'yearly', priority: '0.3' },
  { loc: '/terms', paths: ['terms.html', 'src/data/legal.js'], freq: 'yearly', priority: '0.3' },
]

writeFileSync(
  resolve(dist, 'sitemap.xml'),
  `<?xml version="1.0" encoding="UTF-8"?>
<!--
  Generated by scripts/prerender.mjs. The home page sections are anchors on one
  document, not URLs, so they are not listed. 404.html is noindex and absent.
-->
<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">
${urls
  .map(
    (u) => `  <url>
    <loc>${site}${u.loc}</loc>
    <lastmod>${lastmod(u.paths)}</lastmod>
    <changefreq>${u.freq}</changefreq>
    <priority>${u.priority}</priority>
  </url>`,
  )
  .join('\n')}
</urlset>
`,
)

rmSync(tmp, { recursive: true, force: true })
console.log('prerendered', pages.map((p) => p.file).join(', '), '+ llms.txt, sitemap.xml')
